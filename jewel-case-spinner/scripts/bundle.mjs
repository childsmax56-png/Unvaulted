// Packs everything in public/ into src/files.generated.js so the Worker can serve it
// directly from its own code (no separate asset upload needed).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const root = new URL('../public/', import.meta.url).pathname;
const types = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml', '.css': 'text/css; charset=utf-8', '.md': 'text/markdown; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8', '.png': 'image/png', '.ico': 'image/x-icon',
};
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    if (name.startsWith('_')) continue; // _headers etc. are handled in the Worker
    const type = types[extname(name)];
    if (!type) throw new Error(`No content type for ${p}`);
    files['/' + relative(root, p)] = { type, b64: readFileSync(p).toString('base64') };
  }
})(root);
writeFileSync(new URL('../src/files.generated.js', import.meta.url),
  '// Generated by scripts/bundle.mjs. Do not edit.\nexport default ' + JSON.stringify(files) + ';\n');
console.log(`Bundled ${Object.keys(files).length} files`);
